SYSTEM_PATH = "/usr/sbin:/usr/bin:/sbin:/bin"
BOUNDARY_ERRORS = (
    "quiescence_enrollment", "quiescence_namespace", "quiescence_filesystem", "quiescence_mounts",
    "quiescence_handles", "quiescence_visibility", "quiescence_limits",
)


def command(workspace, args, timeout=8, temporary=None):
    return subprocess.run(
        args, cwd=workspace, env={"PATH": SYSTEM_PATH, "LANG": "C", "HOME": str(workspace),
                                 "XDG_RUNTIME_DIR": str(workspace), "TMPDIR": str(temporary or workspace),
                                 "GOMAXPROCS": "1"},
        stdin=subprocess.DEVNULL, capture_output=True, timeout=timeout,
    )


def mount_command(workspace, *args):
    result = command(workspace, args, timeout=10)
    if result.returncode:
        raise RuntimeError(f"fixture_{Path(args[0]).name}")


@contextmanager
def private_store(workspace, name="native"):
    image, mountpoint = workspace / (name + ".ext4"), workspace / name
    with image.open("xb") as temporary:
        temporary.truncate(64 * 1024**2)
    metadata = image.lstat()
    assert stat.S_ISREG(metadata.st_mode) and metadata.st_uid == 0 and metadata.st_nlink == 1
    mountpoint.mkdir(mode=0o700)
    mount_command(workspace, "mkfs.ext4", "-q", "-F", "-m", "0", "-E",
                  "lazy_itable_init=0,lazy_journal_init=0", image)
    mount_command(workspace, "mount", "-t", "ext4", "-o", "loop,nodev,nosuid", image, mountpoint)
    try:
        mount_command(workspace, "mount", "--make-private", mountpoint)
        assert mountpoint.is_mount() and mountpoint.stat().st_dev != workspace.stat().st_dev
        store = mountpoint / "worker"
        store.mkdir(mode=0o700)
        yield mountpoint, store
    finally:
        mount_command(workspace, "umount", mountpoint)
        assert not mountpoint.is_mount()
        for _ in range(3):
            loop = command(workspace, ("losetup", "-j", image))
            if loop.returncode == 0 and not loop.stdout.strip():
                break
            time.sleep(0.2)
        else:
            raise AssertionError("owned_loop_still_attached")


def wait_for_worker(proc, sock):
    deadline = time.monotonic() + 9
    while time.monotonic() < deadline:
        assert proc.poll() is None, "strict_daemon_exited"
        if sock.is_socket():
            with socket.socket(socket.AF_UNIX) as peer:
                peer.settimeout(0.3)
                try:
                    peer.connect(str(sock))
                except (ConnectionRefusedError, TimeoutError):
                    time.sleep(0.1)
                    continue
                pid, uid, _ = struct.unpack("3i", peer.getsockopt(socket.SOL_SOCKET, socket.SO_PEERCRED, 12))
                fields = {}
                for line in Path(f"/proc/{pid}/status").read_text().splitlines():
                    name, _, value = line.partition(":")
                    if name in ("PPid", "NSpid"):
                        fields[name] = [int(part) for part in value.split()]
                assert uid == 0 and fields["PPid"] == [proc.pid]
                assert len(fields["NSpid"]) > 1 and fields["NSpid"][-1] == 1
                return SimpleNamespace(pid=pid)
        time.sleep(0.1)
    raise RuntimeError("strict_daemon_deadline")


def rejection(workspace, args, reasons=BOUNDARY_ERRORS):
    result = command(workspace, args)
    observed = [reason for reason in reasons if reason.encode() in result.stderr]
    assert result.returncode != 0 and not result.stdout.strip() and len(observed) == 1, "unclassified_denial"
    return observed[0]


def digest_stores(store, fixture):
    digests = fixture["database_digests"](store)
    history = store / "history.db"
    info = history.lstat()
    assert stat.S_ISREG(info.st_mode) and info.st_nlink == 1 and info.st_uid == 0
    assert 0 < info.st_size <= 128 * 1024**2
    with history.open("rb") as database:
        digests["history.db"] = hashlib.file_digest(database, "sha256").hexdigest()
    return digests


def verify_trial_backing(workspace, store, candidate, graph):
    """Read only the exact file and blob generated by this isolated producer."""
    producer = runpy.run_path(str(workspace / "check-buildkit-native.py"))
    with tarfile.open(workspace / "source.oci.tar", "r:") as archive:
        index = json.loads(producer["archive_bytes"](archive, "index.json"))
        manifest_bytes = producer["oci_blob"](archive, index["manifests"], producer["OCI_MANIFEST"])
        manifest = json.loads(manifest_bytes)
        layer = producer["oci_blob"](archive, manifest["layers"], producer["OCI_LAYER"])
    with tarfile.open(fileobj=io.BytesIO(layer), mode="r:") as archive:
        assert [member.name.removeprefix("./") for member in archive.getmembers()] == [producer["OWNED_FILE"]]
        payload = producer["archive_bytes"](archive, producer["OWNED_FILE"])
    assert payload.startswith(b"DSG dedicated worker synthetic project ")

    native = store / "runc-native"
    device = store.stat().st_dev

    def read_exact(path, expected, inode=None):
        assert path.parent.resolve(strict=True) == path.parent
        fd = os.open(path, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW | os.O_NONBLOCK)
        try:
            info = os.fstat(fd)
            assert stat.S_ISREG(info.st_mode) and info.st_dev == device and info.st_nlink == 1
            assert info.st_uid == 0 and 0 < info.st_size == len(expected) <= 65536
            assert inode is None or info.st_ino == inode
            with os.fdopen(fd, "rb", closefd=False) as source:
                assert source.read(len(expected) + 1) == expected
            after = os.fstat(fd)
            assert (info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns) == (
                after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns,
            )
        finally:
            os.close(fd)
        return hashlib.sha256(expected).hexdigest()

    backing = graph["native_allocations"]
    directory = native / "snapshots/snapshots"
    children = list(directory.iterdir())
    assert len(children) <= 16
    matched = []
    for child in children:
        entry = child.lstat()
        if entry.st_ino == backing["snapshot"]["root_inode"]:
            assert re.fullmatch(r"[0-9]{1,20}", child.name) and stat.S_ISDIR(entry.st_mode)
            assert entry.st_dev == device and entry.st_uid == 0
            matched.append(child)
    assert len(matched) == 1
    assert backing["snapshot"]["entries"] == 2
    assert [entry.name for entry in matched[0].iterdir()] == [producer["OWNED_FILE"]]
    snapshot_sha = read_exact(matched[0] / producer["OWNED_FILE"], payload)
    blob_sha = hashlib.sha256(layer).hexdigest()
    assert blob_sha == candidate["verified_layer_sha256"] == backing["blob"]["declared_sha256"]
    read_exact(native / "content/blobs/sha256" / blob_sha, layer, backing["blob"]["root_inode"])
    manifest_sha = hashlib.sha256(manifest_bytes).hexdigest()
    assert graph["retention_ownership"]["incoming_content_key_sha256"] == hashlib.sha256(
        f"sha256:{manifest_sha}".encode("ascii"),
    ).hexdigest()
    read_exact(native / "content/blobs/sha256" / manifest_sha, manifest_bytes)
    return {"snapshot_payload_sha256": snapshot_sha, "blob_sha256": blob_sha,
            "incoming_oci_manifest_sha256": manifest_sha}


def qualify_native_writes(workspace, tests_hash):
    fixture = runpy.run_path(str(workspace / "check-dedicated-buildkit-fence.py"))
    tests = fixture["check_binary"](workspace, "dsg-cache-tests", tests_hash)
    with private_store(workspace, "native-write") as (mountpoint, store):
        assert not os.statvfs(store).f_flag & os.ST_RDONLY and mountpoint.is_mount()
        result = command(
            workspace, (tests, "-test.run", "^TestDSGNative", "-test.v", "-test.parallel", "1",
                        "-test.timeout", "35s"), timeout=40, temporary=store,
        )
        if result.returncode:
            site = re.search(rb"dsg_native_([a-z_]+)_linux_test\.go:(\d{1,4}):", result.stdout)
            location = "_" + "_".join(item.decode("ascii") for item in site.groups()) if site else ""
            raise AssertionError("native_write_recovery_tests" + location)
        lines = result.stdout.decode("utf-8").splitlines()
        passed = [match[1] for line in lines
                  if (match := re.match(r"^--- PASS: (TestDSGNative[A-Za-z0-9]+) ", line))]
        journal_stages = [match[1] for line in lines if (match := re.match(
            r"^\s+--- PASS: TestDSGNativeJournalRecovery/(solver|lease|snapshot|blob|cache) ", line,
        ))]
        backing = [match[1] for line in lines if (match := re.match(
            r"^\s+--- PASS: TestDSGNativeBackingRecovery/(snapshot|blob) ", line,
        ))]
        deletion = [match[1] for line in lines if (match := re.match(
            r"^\s+--- PASS: TestDSGNativeDeletionJournalRecovery/([a-z-]+) ", line,
        ))]
        deletion_proof = [match.groups() for line in lines if (match := re.search(
            r"\bnative-backing-deletion-qualification-v1 snapshot_calls=(\d+) blob_calls=(\d+) "
            r"recovery_calls=(\d+) non_target_changes=(\d+) production_receipts=(\d+)$", line,
        ))]
        assert {"TestDSGNativeJournalRecovery", "TestDSGNativeBackingRecovery",
                "TestDSGNativeCacheMetadataRecovery", "TestDSGNativeDeletionJournalRecovery"} <= set(passed)
        assert set(journal_stages) == {"solver", "lease", "snapshot", "blob", "cache"}
        assert set(backing) == {"snapshot", "blob"}
        assert any("native-five-stage-trial-v1" in line for line in lines)
        assert set(deletion) == {"snapshot", "blob", "missing-pre-effect", "partial-postcondition"}
        assert deletion_proof == [("1", "1", "0", "0", "0")]
        counts = dict(zip(("snapshot_calls", "blob_calls", "recovery_calls", "non_target_changes",
                           "production_receipts"), map(int, deletion_proof[0]), strict=True))
    return {"passed": passed, "journal_stages": journal_stages, "independent_stages": [*backing, "cache"],
            "trial_proof": "native-five-stage-trial-v1",
            "actual_synthetic_backing_deletion": {"proof": "native-backing-deletion-qualification-v1",
                                                  "cases": deletion, **counts},
            "writable_ext4": True, "owned_loop_released": True}


def require_private_boundary(workspace):
    assert sys.platform == "linux" and os.uname().machine == "aarch64" and os.geteuid() == 0
    assert workspace.resolve(strict=True) == workspace and workspace.is_mount()
    assert workspace.stat().st_uid == 0 and stat.S_IMODE(workspace.stat().st_mode) == 0o700
    assert os.readlink("/proc/self/ns/pid") == os.readlink("/proc/1/ns/pid")
    for kind in ("net", "mnt"):
        assert os.readlink(f"/proc/self/ns/{kind}") != os.readlink(f"/proc/1/ns/{kind}")
    assert not Path("/run/docker.sock").is_socket() and not Path("/run/containerd/containerd.sock").is_socket()


def qualify(workspace, daemon_hash, client_hash):
    fixture = runpy.run_path(str(workspace / "check-dedicated-buildkit-fence.py"))
    daemon = fixture["check_binary"](workspace, "buildkitd", daemon_hash)
    client = fixture["check_binary"](workspace, "buildctl", client_hash)
    config, sock = workspace / "buildkitd.toml", workspace / "native.sock"
    config.write_text(
        '[worker.oci]\nenabled = true\nsnapshotter = "native"\nrootless = false\ngc = false\n'
        'noProcessSandbox = false\nmax-parallelism = 1\nnetworkMode = "host"\n'
        '[worker.containerd]\nenabled = false\n[cdi]\ndisabled = true\n[history]\nmaxEntries = 0\n',
        encoding="ascii",
    )
    addr = f"unix://{sock}"
    with private_store(workspace) as (mountpoint, store):
        args = (daemon, "--dsg-dedicated-worker", "--dsg-require-quiescence", "--config", config,
                "--root", store, "--addr", addr, "--otel-socket-path", workspace / "trace.sock")
        inspect = (daemon, "--dsg-inspect-dedicated-worker", "--dsg-require-quiescence",
                   "--config", config, "--root", store)
        assert rejection(workspace, args) == "quiescence_namespace"
        isolated = ("unshare", "--pid", "--fork", "--kill-child", "--mount-proc", *args)
        with fixture["child"](isolated, workspace) as running:
            peer = wait_for_worker(running, sock)
            candidate = fixture["create_cache_evidence"](workspace, client, addr, peer, sock)
        check = (*inspect, "--dsg-record-id", candidate["id"])
        writable_rejection = rejection(workspace, check)
        assert writable_rejection == "quiescence_filesystem"
        mount_command(workspace, "mount", "-o", "remount,ro", mountpoint)
        database = store / "runc-native/metadata_v2.db"
        try:
            fd = os.open(database, os.O_RDWR | os.O_CLOEXEC | os.O_NOFOLLOW)
        except OSError as issue:
            assert issue.errno == errno.EROFS
        else:
            os.close(fd)
            raise AssertionError("root_write_open_allowed")
        with database.open("rb"):
            assert rejection(workspace, check) == "quiescence_handles"

        alias = workspace / "native-alias"
        alias.mkdir(mode=0o700)
        mount_command(workspace, "mount", "--bind", mountpoint, alias)
        try:
            assert rejection(workspace, check) == "quiescence_mounts"
        finally:
            mount_command(workspace, "umount", alias)
        before = digest_stores(store, fixture)
        observed = command(workspace, check, timeout=12)
        if observed.returncode:
            failure = next((reason for reason in BOUNDARY_ERRORS if reason.encode() in observed.stderr), "unknown")
            raise AssertionError("strict_read_" + failure)
        assert 0 < len(observed.stdout) <= 32768
        evidence = json.loads(observed.stdout)
        assert evidence["record"]["id"] == candidate["id"] and evidence["record"]["record_present"]
        expected = ("filesystem_read_only", "executor_namespace_gone", "mounts_clear", "external_handles_clear")
        assert all(evidence["quiescence"][name] is True for name in expected)
        graph = evidence["graph"]
        ownership = graph["retention_ownership"]
        assert graph["disposition"] == "preserve" and graph["unverified"]
        assert re.fullmatch(r"[a-f0-9]{64}", graph["references_sha256"])
        assert graph["cache"]["committed"] and graph["solver"]["result_nodes"] > 0
        assert evidence["history_tx"] > 0 and graph["external"]["history_records"] >= 0
        assert graph["transitive"]["solver"]["result_nodes"] > 0
        assert graph["transitive"]["cache_records"]
        assert graph["transitive"]["gc_labels"]["content_nodes"] == 2
        assert ownership["checked"] and not ownership["exclusive"]
        assert ownership["reason"] == "foreign_or_unresolved_retention_edge"
        assert ownership["record_lease"] and ownership["variant_lease"] and not ownership["view_lease"]
        assert ownership["owned_roots"] == graph["transitive"]["gc_labels"]["roots"] == 2
        assert ownership["owned_child_snapshots"] == graph["native_snapshot"]["children"] == 1
        for kind in ("snapshot", "blob"):
            allocation = graph["native_allocations"][kind]
            assert re.fullmatch(r"[a-f0-9]{64}", allocation["metadata_sha256"])
            assert allocation["entries"] > 0 and allocation["content_verified"] is False
        assert re.fullmatch(r"[a-f0-9]{64}", graph["native_allocations"]["blob"]["declared_sha256"])
        candidate["generated_backing"] = verify_trial_backing(workspace, store, candidate, graph)
        repeated = command(workspace, check, timeout=12)
        assert repeated.returncode == 0 and json.loads(repeated.stdout) == evidence
        assert digest_stores(store, fixture) == before
        candidate["offline"] = evidence
        candidate["disposition"] = "preserve"
        candidate["reclamation_checks"] = {
            "retention_roots": graph["transitive"]["gc_labels"]["roots"],
            "snapshot_children": graph["native_snapshot"]["children"],
            "retention_ownership": ownership,
            "unverified": graph["unverified"],
            "approval_requested": False,
        }
        snapshot = json.dumps(candidate, sort_keys=True, separators=(",", ":")).encode()
        candidate["evidence_sha256"] = hashlib.sha256(snapshot).hexdigest()
    return {
        "daemon_started": True, "separate_pid_namespace": True, "owned_loop_released": True,
        "root_writable_mount_denied": True, "root_write_open_denied": True, "independent_handle_denied": True,
        "bind_alias_denied": True, "unchanged_database_count": len(before),
        "read_only_candidate": candidate, "actual_cache_deletion_requests": 0, "prune_requests": 0,
    }


if __name__ == "__main__":
    os.umask(0o077)
    native = None
    try:
        workspace = Path(sys.argv[1])
        require_private_boundary(workspace)
        native = qualify_native_writes(workspace, sys.argv[4])
        result = qualify(workspace, sys.argv[2], sys.argv[3])
        result["native_writable_recovery"] = native
    except (AssertionError, OSError, KeyError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        location = error.__traceback__
        local_line = location.tb_lineno
        while location is not None:
            if location.tb_frame.f_code.co_filename == __file__:
                local_line = location.tb_lineno
            location = location.tb_next
        category = str(error) if re.fullmatch(r"[a-z_0-9]{1,80}", str(error)) else None
        print(json.dumps({"fixture_error": type(error).__name__, "line": local_line,
                          "category": category, "errno": getattr(error, "errno", None),
                          "native_writable_recovery": native}), flush=True)
        raise SystemExit(1) from None
    print(json.dumps(result, sort_keys=True), flush=True)
